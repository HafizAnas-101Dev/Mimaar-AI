const DICTS: Record<Language, Record<Key, string>> = { en, ar, ur };
const STORAGE_KEY = "mimaar.lang";

interface I18n {
  lang: Language;
  dir: "ltr" | "rtl";
  setLang: (lang: Language) => void;
  t: (key: Key) => string;
  el: (type: string) => string;
}

const I18nContext = createContext<I18n | null>(null);

function initialLang(): Language {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "ar" || saved === "ur") return saved;
  } catch {
    /* storage unavailable */
  }
  return "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(initialLang);
  const dir = lang === "en" ? "ltr" : "rtl";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  function setLang(next: Language) {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* storage unavailable */
    }
  }

  const dict = DICTS[lang];
  const t = (key: Key) => dict[key] ?? en[key];
  const el = (type: string) => dict[`el.${type}` as Key] ?? type;

  return <I18nContext.Provider value={{ lang, dir, setLang, t, el }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
